"""Generate include/__metal_simd.h: simdgroup and quadgroup functions and 8x8
simdgroup matrices as AIR calls (probes/p33_simd.metal; FORMAT.md).

usage: python3 gen_simd.py > include/__metal_simd.h  (included inside namespace metal)
"""

AI = '__attribute__((always_inline)) inline'
CV = 'extern "C" __attribute__((convergent))'
ELEMS = [('float', 'f32'), ('half', 'f16'), ('int', 's.i32'), ('uint', 'u.i32'), ('short', 's.i16'), ('ushort', 'u.i16')]
REDUCE = ['simd_sum', 'simd_product', 'simd_max', 'simd_min', 'simd_prefix_inclusive_sum', 'simd_prefix_exclusive_sum',
          'simd_prefix_inclusive_product', 'simd_broadcast_first', 'quad_sum', 'quad_max', 'quad_broadcast_first']
BITWISE = ['simd_and', 'simd_or', 'simd_xor']          # integers only
LANE = ['simd_shuffle', 'simd_shuffle_xor', 'simd_shuffle_up', 'simd_shuffle_down', 'simd_broadcast',
        'simd_shuffle_rotate_up', 'simd_shuffle_rotate_down', 'quad_shuffle', 'quad_shuffle_xor', 'quad_broadcast']


def suffix(e, n):
    """f32 -> v4f32; s.i32 -> s.v4i32"""
    sign, base = e.split('.') if '.' in e else (None, e)
    v = 'v%d' % n if n > 1 else ''
    return ('%s.' % sign if sign else '') + v + base


def emit():
    out = ['// Generated by gen_simd.py: simdgroup/quadgroup functions and matrices as AIR calls.', '#pragma once']
    for t, e in ELEMS:
        for n in (1, 2, 3, 4):
            ty = t if n == 1 else '%s%d' % (t, n)
            s = suffix(e, n)
            c = s.replace('.', '_')
            fns = REDUCE + (BITWISE if t not in ('float', 'half') else [])
            for fn in fns:
                out.append('%s %s __air_%s_%s(%s) __AIR("air.%s.%s");' % (CV, ty, fn, c, ty, fn, s))
                out.append('%s %s %s(%s x) { return __air_%s_%s(x); }' % (AI, ty, fn, ty, fn, c))
            for fn in LANE:
                out.append('%s %s __air_%s_%s(%s, ushort) __AIR("air.%s.%s");' % (CV, ty, fn, c, ty, fn, s))
                out.append('%s %s %s(%s x, ushort l) { return __air_%s_%s(x, l); }' % (AI, ty, fn, ty, fn, c))
    # 8x8 simdgroup matrices: a <64 x T> per thread; load/store name the pointer's
    # address space (p1 device, p3 threadgroup): %AS% is filled in by the driver.
    # thread_elements()[k] is element k of the per-thread vector (observed: extractelement)
    out.append('template <class T> struct __sgm_elements { T *p; __attribute__((always_inline)) T &operator[](int k) const { return p[k]; } };')
    out.append('template <class T, int R, int C> struct simdgroup_matrix { __vector<T, R * C> __m;'
               ' __attribute__((always_inline)) __sgm_elements<T> thread_elements() { return {(T *)&__m}; } };')
    for t, e in (('float', 'f32'), ('half', 'f16')):
        v = 'v64%s' % e
        out.append('typedef simdgroup_matrix<%s, 8, 8> simdgroup_%s8x8;' % (t, t))
        out.append('extern "C" __vector<%s, 64> __air_sgm_fill_%s(%s) __AIR("air.simdgroup_matrix_8x8_init_filled.%s.%s");' % (t, e, t, v, e))
        out.append('extern "C" __attribute__((convergent)) __vector<%s, 64> __air_sgm_load_%s(const %s *, long2, long2, long2) __AIR("air.simdgroup_matrix_8x8_load.%s.p%%AS%%%s");' % (t, e, t, v, e))
        out.append('extern "C" __attribute__((convergent)) void __air_sgm_store_%s(__vector<%s, 64>, %s *, long2, long2, long2) __AIR("air.simdgroup_matrix_8x8_store.%s.p%%AS%%%s");' % (e, t, t, v, e))
        out.append('%s void simdgroup_load(simdgroup_matrix<%s, 8, 8> &m, const %s *src, ulong elements_per_row = 8, ulong2 origin = ulong2{0, 0}, bool transpose = false) {'
                   ' long2 st = transpose ? long2{(long)elements_per_row, 1} : long2{1, (long)elements_per_row};'
                   ' long2 o = transpose ? long2{(long)origin.y, (long)origin.x} : long2{(long)origin.x, (long)origin.y};'
                   ' m.__m = __air_sgm_load_%s(src, long2{8, 8}, st, o); }' % (AI, t, t, e))
        out.append('%s void simdgroup_store(simdgroup_matrix<%s, 8, 8> m, %s *dst, ulong elements_per_row = 8, ulong2 origin = ulong2{0, 0}, bool transpose = false) {'
                   ' long2 st = transpose ? long2{(long)elements_per_row, 1} : long2{1, (long)elements_per_row};'
                   ' long2 o = transpose ? long2{(long)origin.y, (long)origin.x} : long2{(long)origin.x, (long)origin.y};'
                   ' __air_sgm_store_%s(m.__m, dst, long2{8, 8}, st, o); }' % (AI, t, t, e))
    out.append('template <class T, int R, int C> %s simdgroup_matrix<T, R, C> make_filled_simdgroup_matrix(T v);' % AI)
    for t, e in (('float', 'f32'), ('half', 'f16')):
        out.append('template <> %s simdgroup_matrix<%s, 8, 8> make_filled_simdgroup_matrix<%s, 8, 8>(%s v) { return {__air_sgm_fill_%s(v)}; }' % (AI, t, t, t, e))
    # multiply-accumulate: d = a * b + c, named by result and operand types (observed)
    for d, a, c in (('float', 'float', 'float'), ('float', 'half', 'float'), ('half', 'half', 'half')):
        de, ae, ce = ('v64f32' if d == 'float' else 'v64f16'), ('v64f32' if a == 'float' else 'v64f16'), ('v64f32' if c == 'float' else 'v64f16')
        fn = '__air_sgm_mac_%s_%s_%s' % (d, a, c)
        out.append('extern "C" __attribute__((convergent)) __vector<%s, 64> %s(__vector<%s, 64>, __vector<%s, 64>, __vector<%s, 64>) __AIR("air.simdgroup_matrix_8x8_multiply_accumulate.%s.%s.%s.%s");'
                   % (d, fn, a, a, c, de, ae, ae, ce))
        out.append('%s void simdgroup_multiply_accumulate(thread simdgroup_matrix<%s, 8, 8> &r, simdgroup_matrix<%s, 8, 8> a, simdgroup_matrix<%s, 8, 8> b, simdgroup_matrix<%s, 8, 8> c) { r.__m = %s(a.__m, b.__m, c.__m); }'
                   % (AI, d, a, a, c, fn))
        if a == c:
            out.append('%s void simdgroup_multiply(thread simdgroup_matrix<%s, 8, 8> &r, simdgroup_matrix<%s, 8, 8> a, simdgroup_matrix<%s, 8, 8> b) { r.__m = %s(a.__m, b.__m, __air_sgm_fill_%s((%s)0)); }'
                       % (AI, d, a, a, fn, 'f32' if c == 'float' else 'f16', c))
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    print(emit(), end='')
