fn generic(x: usize, y: usize) -> (i8, i8) {
    let n = SIZE;
    let (left, right, top, bottom) = (x, n - 1 - x, y, n - 1 - y);
    // The nearer edge on each axis, its distance and which side it is.
    let (dx, x_near) = if left <= right { (left, true) } else { (right, false) };
    let (dy, y_near) = if top <= bottom { (top, true) } else { (bottom, false) };
    let k = dx as isize - dy as isize;
    let (sx, sy) = (if x_near { 1 } else { -1 }, if y_near { 1 } else { -1 });
    let (mut vx, mut vy): (i16, i16) = if k.abs() <= 9 {
        let (a, b) = DIAGONAL[(k + 9) as usize];
        (a as i16 * sx, b as i16 * sy)
    } else if k < 0 {
        (-127 * sx, 0)
    } else {
        (0, -127 * sy)
    };
    let ramp = |v: i16, d: usize, near: bool| -> i16 {
        let table = if near { &RAMP_NEAR } else { &RAMP_FAR };
        if v.abs() != 127 || d >= table.len() { v } else { table[d] as i16 * v.signum() }
    };
    vx = ramp(vx, dx, x_near);
    vy = ramp(vy, dy, y_near);
    (vx as i8, vy as i8)
}

/// The texture's bytes: x then y per pixel, rows top to bottom.
pub fn opaque() -> Vec<u8> {
    let n = SIZE;
    let mut v: Vec<(i8, i8)> = (0..n * n).map(|i| generic(i % n, i / n)).collect();
    let mut set = |x: usize, y: usize, p: (i8, i8)| v[y * n + x] = p;
    for &(a, b, x, y) in &TOP_LEFT {
        let (a, b) = (a as usize, b as usize);
        set(a, b, (x, y));
        set(b, a, (y, x));
    }
    for &(a, b, x, y) in &TOP_RIGHT {
        let (a, b) = (a as usize, b as usize);
        set(n - 1 - a, b, (x, y));
        set(b, n - 1 - a, (y, x));
    }
    for &(a, b, x, y) in &BOTTOM_RIGHT {
        let (a, b) = (a as usize, b as usize);
        set(n - 1 - a, n - 1 - b, (x, y));
        set(n - 1 - b, n - 1 - a, (y, x));
    }
    let half = n / 2;
    for &(u, w, x, y) in &CENTRE {
        for (u, w, x, y) in [(u, w, x, y), (w, u, y, x)] {
            let (u, w) = (u as usize, w as usize);
            for (mx, my) in [(1i8, 1i8), (-1, 1), (1, -1), (-1, -1)] {
                let px = if mx > 0 { half + u } else { half - 1 - u };
                let py = if my > 0 { half + w } else { half - 1 - w };
                set(px, py, (x * mx, y * my));
            }
        }
    }
    v.iter().flat_map(|(x, y)| [*x as u8, *y as u8]).collect()
}
