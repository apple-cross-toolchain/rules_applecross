"""Generate include/metal_math from the AIR names Xcode's compiler emits
(probes/p30_math.metal; FORMAT.md) and the MSL specification's definitions.

usage: python3 gen_math.py > include/__metal_math.h  (included inside namespace metal)
"""

FLOAT_VECS = ['float', 'float2', 'float3', 'float4']
HALF_VECS = ['half', 'half2', 'half3', 'half4']
INT_TYPES = [('char', 's', 'i8'), ('uchar', 'u', 'i8'), ('short', 's', 'i16'), ('ushort', 'u', 'i16'),
             ('int', 's', 'i32'), ('uint', 'u', 'i32'), ('long', 's', 'i64'), ('ulong', 'u', 'i64')]

# Observed: under fast math, float uses air.fast_<fn>; half never does; these never do.
NEVER_FAST = {'sign', 'mix', 'fma'}
UNARY = ['sin', 'cos', 'tan', 'asin', 'acos', 'atan', 'sinh', 'cosh', 'tanh', 'asinh', 'acosh', 'atanh',
         'exp', 'exp2', 'exp10', 'log', 'log2', 'log10', 'sqrt', 'rsqrt', 'fabs', 'floor', 'ceil',
         'round', 'rint', 'trunc', 'fract', 'saturate', 'sign', 'sinpi', 'cospi', 'tanpi']
BINARY = ['pow', 'powr', 'atan2', 'fmod', 'fmax', 'fmin']
TERNARY = ['clamp', 'mix', 'fma', 'fmax3', 'fmin3', 'fmedian3']
ALIASES = {'abs': 'fabs', 'max': 'fmax', 'min': 'fmin', 'max3': 'fmax3', 'min3': 'fmin3', 'median3': 'fmedian3'}
INT_BINARY = {'min': 'min', 'max': 'max', 'absdiff': 'abs_diff', 'addsat': 'add_sat', 'subsat': 'sub_sat'}
INT_UNARY_SIGNED = {'abs': 'abs'}
INT_UNARY_UNSIGNED = {'popcount': 'popcount', 'clz': 'clz', 'ctz': 'ctz'}


def suffix(t):
    """AIR's type suffix: f32, v3f16, i32, v4i8."""
    base = {'float': 'f32', 'half': 'f16'}
    for name, _, s in INT_TYPES:
        base[name] = s
    n = t[-1] if t[-1] in '234' else ''
    e = t[:-1] if n else t
    return ('v%s' % n if n else '') + base[e]


def int_vecs(name):
    return [name] + [name + n for n in '234']


def fn_name(fn, t):
    """Float functions get the fast_ prefix under fast math (a macro decides)."""
    if t.startswith('half') or fn in NEVER_FAST:
        return '"air.%s.%s"' % (fn, suffix(t))
    return '__MSL_F(%s) ".%s"' % (fn, suffix(t))


def lib_fract(t):
    """The Metal library's fract Xcode calls outside macOS: ___metal_fract_v2float."""
    n = t[-1] if t[-1] in '234' else ''
    return '___metal_fract_%s%s' % ('v' + n if n else '', t.rstrip('234'))


def fract(t, ns=None):
    """fract as Xcode has it (probes/p46_fract.metal). On macOS the AIR function
    like every other; elsewhere the library's ___metal_fract_<type>(x, mode),
    mode 0 fast or 3 precise, for vectors and for a float that isn't fast."""
    AI = '__attribute__((always_inline)) inline'
    scalar = t.rstrip('234')
    if ns is None:
        air = fn_name('fract', t)
        mode = '__MSL_FRACT_MODE'
        lib = '!defined(__MSL_TARGET_MACOS)' if t != scalar else '!defined(__MSL_TARGET_MACOS) && !defined(__FAST_MATH__)'
    else:
        air = '"air.%sfract.%s"' % ('fast_' if ns == 'fast' else '', suffix(t))
        mode = '0' if ns == 'fast' else '3'
        lib = '!defined(__MSL_TARGET_MACOS)' if t != scalar or ns == 'precise' else '0'
    name = '__air_%sfract_%s' % (ns + '_' if ns else '', suffix(t).replace('.', '_'))
    air_fn = ['extern "C" %s %s(%s) __AIR(%s);' % (t, name, t, air),
              '%s %s fract(%s x) { return %s(x); }' % (AI, t, t, name)]
    if scalar == 'half' and t == scalar or lib == '0':
        return air_fn
    return ['#if %s' % lib, '%s %s fract(%s x) { return %s(x, %s); }' % (AI, t, t, lib_fract(t), mode), '#else'] + air_fn + ['#endif']


def emit():
    out = ['// Generated by gen_math.py: math functions as AIR calls.',
           '#pragma once',
           '// fdim: the MSL specification\'s definition (Xcode inlines it too)',
           'template <class V> __attribute__((always_inline)) inline V __msl_fdim(V x, V y) {',
           '  if constexpr (__elem<V>::n == 1) return x > y ? x - y : (V)0; else { V r; for (int k = 0; k < __elem<V>::n; k++) r[k] = x[k] > y[k] ? x[k] - y[k] : 0; return r; }',
           '}',
           '#ifdef __FAST_MATH__',
           '#define __MSL_F(n) "air.fast_" #n',
           '#else',
           '#define __MSL_F(n) "air." #n',
           '#endif',
           '#ifdef __FAST_MATH__',
           '#define __MSL_FRACT_MODE 0',
           '#else',
           '#define __MSL_FRACT_MODE 3',
           '#endif']
    for t in FLOAT_VECS + HALF_VECS:
        if t != 'half':
            out.append('extern "C" %s %s(%s, int);' % (t, lib_fract(t), t))
    AI = '__attribute__((always_inline)) inline'
    for vecs in (FLOAT_VECS, HALF_VECS):
        scalar = vecs[0]
        for t in vecs:
            sfx = suffix(t).replace('.', '_')
            for fn in UNARY:
                if fn == 'fract':
                    out += fract(t)
                    continue
                out.append('extern "C" %s __air_%s_%s(%s) __AIR(%s);' % (t, fn, sfx, t, fn_name(fn, t)))
                out.append('%s %s %s(%s x) { return __air_%s_%s(x); }' % (AI, t, fn, t, fn, sfx))
            for fn in BINARY:
                out.append('extern "C" %s __air_%s_%s(%s, %s) __AIR(%s);' % (t, fn, sfx, t, t, fn_name(fn, t)))
                out.append('%s %s %s(%s x, %s y) { return __air_%s_%s(x, y); }' % (AI, t, fn, t, t, fn, sfx))
                if t != scalar:
                    out.append('%s %s %s(%s x, %s y) { return __air_%s_%s(x, (%s)y); }' % (AI, t, fn, t, scalar, fn, sfx, t))
            for fn in TERNARY:
                out.append('extern "C" %s __air_%s_%s(%s, %s, %s) __AIR(%s);' % (t, fn, sfx, t, t, t, fn_name(fn, t)))
                out.append('%s %s %s(%s x, %s y, %s z) { return __air_%s_%s(x, y, z); }' % (AI, t, fn, t, t, t, fn, sfx))
                if t != scalar:
                    out.append('%s %s %s(%s x, %s y, %s z) { return __air_%s_%s(x, y, z); }' % (AI, t, fn, t, t, scalar, fn, sfx))
                    out.append('%s %s %s(%s x, %s y, %s z) { return __air_%s_%s(x, (%s)y, (%s)z); }' % (AI, t, fn, t, scalar, scalar, fn, sfx, t, t))
            for alias, fn in ALIASES.items():
                if fn in UNARY:
                    out.append('%s %s %s(%s x) { return %s(x); }' % (AI, t, alias, t, fn))
                elif fn in BINARY:
                    out.append('%s %s %s(%s x, %s y) { return %s(x, y); }' % (AI, t, alias, t, t, fn))
                    if t != scalar:
                        out.append('%s %s %s(%s x, %s y) { return %s(x, y); }' % (AI, t, alias, t, scalar, fn))
                else:
                    out.append('%s %s %s(%s x, %s y, %s z) { return %s(x, y, z); }' % (AI, t, alias, t, t, t, fn))
            # step: 0 where x < edge, else 1 (MSL specification)
            out.append('%s %s step(%s e, %s x) { %s r; for (int k = 0; k < __elem<%s>::n; k++) r[k] = x[k] < e[k] ? 0 : 1; return r; }'
                       % (AI, t, t, t, t, t) if t != scalar else
                       '%s %s step(%s e, %s x) { return x < e ? (%s)0 : (%s)1; }' % (AI, t, t, t, t, t))
            if t != scalar:
                out.append('%s %s step(%s e, %s x) { return step((%s)e, x); }' % (AI, t, scalar, t, t))
                n = t[-1]
                out.append('extern "C" %s __air_dot_%s(%s, %s) __AIR("air.dot.%s");' % (scalar, suffix(t), t, t, suffix(t)))
                out.append('%s %s dot(%s a, %s b) { return __air_dot_%s(a, b); }' % (AI, scalar, t, t, suffix(t)))
                out.append('%s %s length(%s v) { return sqrt(dot(v, v)); }' % (AI, scalar, t))
                out.append('%s %s length_squared(%s v) { return dot(v, v); }' % (AI, scalar, t))
                out.append('%s %s distance(%s a, %s b) { return length(a - b); }' % (AI, scalar, t, t))
                out.append('%s %s distance_squared(%s a, %s b) { return dot(a - b, a - b); }' % (AI, scalar, t, t))
                out.append('%s %s normalize(%s v) { return v * rsqrt(dot(v, v)); }' % (AI, t, t))
                out.append('%s %s reflect(%s i, %s n) { return i - (%s)2 * dot(n, i) * n; }' % (AI, t, t, t, scalar))
                out.append('%s %s faceforward(%s n, %s i, %s r) { return dot(r, i) < 0 ? n : -n; }' % (AI, t, t, t, t))
                if n == '3':
                    out.append('%s %s cross(%s a, %s b) { return %s{a.y * b.z - a.z * b.y, a.z * b.x - a.x * b.z, a.x * b.y - a.y * b.x}; }'
                               % (AI, t, t, t, t))
            # smoothstep (MSL specification)
            out.append('%s %s smoothstep(%s e0, %s e1, %s x) { %s t = clamp((x - e0) / (e1 - e0), (%s)0, (%s)1); return t * t * ((%s)3 - (%s)2 * t); }'
                       % (AI, t, t, t, t, t, scalar, scalar, scalar, scalar))
            if t != scalar:
                out.append('%s %s smoothstep(%s e0, %s e1, %s x) { return smoothstep((%s)e0, (%s)e1, x); }' % (AI, t, scalar, scalar, t, t, t))
    # integers
    for name, sign, _ in INT_TYPES:
        for t in int_vecs(name):
            sfx = suffix(t)
            c = sfx.replace('.', '_')
            for fn, air in INT_BINARY.items():
                out.append('extern "C" %s __air_%s_%s_%s(%s, %s) __AIR("air.%s.%s.%s");' % (t, air, sign, c, t, t, air, sign, sfx))
                out.append('%s %s %s(%s x, %s y) { return __air_%s_%s_%s(x, y); }' % (AI, t, fn, t, t, air, sign, c))
            out.append('extern "C" %s __air_clamp_%s_%s(%s, %s, %s) __AIR("air.clamp.%s.%s");' % (t, sign, c, t, t, t, sign, sfx))
            out.append('%s %s clamp(%s x, %s lo, %s hi) { return __air_clamp_%s_%s(x, lo, hi); }' % (AI, t, t, t, t, sign, c))
            out.append('extern "C" %s __air_abs_%s_%s(%s) __AIR("air.abs.%s.%s");' % (t, sign, c, t, sign, sfx))
            out.append('%s %s abs(%s x) { return __air_abs_%s_%s(x); }' % (AI, t, t, sign, c))
            for fn, air in INT_UNARY_UNSIGNED.items():
                # clz and ctz take LLVM's "zero is undefined" flag, always false (MSL defines them at 0)
                flag = fn in ('clz', 'ctz')
                out.append('extern "C" %s __air_%s_%s_%s(%s%s) __AIR("air.%s.%s");' % (t, air, sign, c, t, ', bool' if flag else '', air, sfx))
                out.append('%s %s %s(%s x) { return __air_%s_%s_%s(x%s); }' % (AI, t, fn, t, air, sign, c, ', false' if flag else ''))
            out.append('extern "C" %s __air_rotate_%s_%s(%s, %s) __AIR("air.rotate.%s");' % (t, sign, c, t, t, sfx))
            out.append('%s %s rotate(%s x, %s y) { return __air_rotate_%s_%s(x, y); }' % (AI, t, t, t, sign, c))
            out.append('%s %s max3(%s a, %s b, %s c) { return max(max(a, b), c); }' % (AI, t, t, t, t))
            out.append('%s %s min3(%s a, %s b, %s c) { return min(min(a, b), c); }' % (AI, t, t, t, t))
    # precise:: and fast:: (float only): air.<fn> and air.fast_<fn> regardless of the default
    for ns, prefix in (('precise', ''), ('fast', 'fast_')):
        out.append('namespace %s {' % ns)
        for t in FLOAT_VECS:
            s = suffix(t)
            for fn in UNARY:
                if fn == 'fract':
                    out += fract(t, ns)
                    continue
                out.append('extern "C" %s __air_%s_%s_%s(%s) __AIR("air.%s%s.%s");' % (t, ns, fn, s, t, prefix, fn, s))
                out.append('%s %s %s(%s x) { return __air_%s_%s_%s(x); }' % (AI, t, fn, t, ns, fn, s))
            for fn in BINARY:
                out.append('extern "C" %s __air_%s_%s_%s(%s, %s) __AIR("air.%s%s.%s");' % (t, ns, fn, s, t, t, prefix, fn, s))
                out.append('%s %s %s(%s x, %s y) { return __air_%s_%s_%s(x, y); }' % (AI, t, fn, t, t, ns, fn, s))
        out.append('}  // namespace %s' % ns)
    # isnan/isinf by bits (fast math may not fold them); copysign, fdim (MSL specification)
    for scalar, bits, ubits, expo, mant in (('float', 'uint', 'uint', '0x7f800000u', '0x7fffffffu'), ('half', 'ushort', 'ushort', '(ushort)0x7c00', '(ushort)0x7fff')):
        out.append('%s bool isnan(%s x) { return (__builtin_bit_cast(%s, x) & %s) > %s; }' % (AI, scalar, bits, mant, expo))
        out.append('%s bool isinf(%s x) { return (__builtin_bit_cast(%s, x) & %s) == %s; }' % (AI, scalar, bits, mant, expo))
        out.append('%s bool isfinite(%s x) { return (__builtin_bit_cast(%s, x) & %s) < %s; }' % (AI, scalar, bits, mant, expo))
        out.append('%s bool signbit(%s x) { return (__builtin_bit_cast(%s, x) >> (sizeof(%s) * 8 - 1)) != 0; }' % (AI, scalar, bits, scalar))
        for n in ('2', '3', '4'):
            t = scalar + n
            out.append('%s __boolvec<%s> isnan(%s x) { __boolvec<%s> r; for (int k = 0; k < %s; k++) r[k] = isnan((%s)x[k]); return r; }' % (AI, n, t, n, n, scalar))
            out.append('%s __boolvec<%s> isinf(%s x) { __boolvec<%s> r; for (int k = 0; k < %s; k++) r[k] = isinf((%s)x[k]); return r; }' % (AI, n, t, n, n, scalar))
        for t in ([scalar] + [scalar + n for n in '234']):
            # copysign in bits, as Xcode's header computes it (a scalar half through int promotion)
            bt = ubits + t[len(scalar):]
            sign, mag = ('0x80000000u', '0x7fffffff') if scalar == 'float' else ('0x8000', '~0x8000' if t == scalar else '0x7fff')
            out.append('%s %s copysign(%s x, %s y) { %s s = __builtin_bit_cast(%s, y) & %s; %s r = (__builtin_bit_cast(%s, x) & %s) | s; return __builtin_bit_cast(%s, r); }'
                       % (AI, t, t, t, bt, bt, sign, bt, bt, mag, t))
            out.append('%s %s fdim(%s x, %s y) { return __msl_fdim(x, y); }' % (AI, t, t, t))
    # derivatives (fragment functions; observed for float)
    for t in FLOAT_VECS:
        for fn in ('dfdx', 'dfdy', 'fwidth'):
            out.append('extern "C" %s __air_%s_%s(%s) __AIR("air.%s.%s");' % (t, fn, suffix(t), t, fn, suffix(t)))
            out.append('%s %s %s(%s x) { return __air_%s_%s(x); }' % (AI, t, fn, t, fn, suffix(t)))
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    print(emit(), end='')
