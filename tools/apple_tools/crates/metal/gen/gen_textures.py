"""Generate include/__metal_textures.h: MSL's texture types as AIR calls, with
the call shapes Xcode's compiler emits (probes/p31_textures.metal; FORMAT.md).
Only operations seen in the probe are generated.

usage: python3 gen_textures.py > include/__metal_textures.h  (included inside namespace metal)
"""

ELEMS = {  # element type -> (AIR suffix, vector, return struct)
    'float': ('v4f32', 'float4', '__ret_v4f32'),
    'half': ('v4f16', 'half4', '__ret_v4f16'),
    'int': ('s.v4i32', 'int4', '__ret_v4i32'),
    'uint': ('u.v4i32', 'uint4', '__ret_v4u32'),
}
AI = '__attribute__((always_inline))'

# kind: (MSL template, AIR kind, sample coord, read coord, array, offset, mips)
KINDS = {
    '1d': ('texture1d', 'texture_1d', 'float', 'uint', False, 'fixed1d', True),
    '1d_array': ('texture1d_array', 'texture_1d_array', 'float', 'uint', True, 'fixed1d', True),
    '2d': ('texture2d', 'texture_2d', 'float2', 'uint2', False, 'int2', True),
    '2d_array': ('texture2d_array', 'texture_2d_array', 'float2', 'uint2', True, 'int2', True),
    '3d': ('texture3d', 'texture_3d', 'float3', 'uint3', False, 'int3', True),
    'cube': ('texturecube', 'texture_cube', 'float3', 'uint2', False, None, True),
    'cube_array': ('texturecube_array', 'texture_cube_array', 'float3', 'uint2', True, None, True),
    '2d_ms': ('texture2d_ms', 'texture_2d_ms', None, 'uint2', False, None, False),
    'buffer': ('texture_buffer', 'texture_buffer_1d', None, 'uint', False, None, False),
}
# Observed operations per kind.
SAMPLE = {'1d', '1d_array', '2d', '2d_array', '3d', 'cube', 'cube_array'}
GATHER = {'2d', '2d_array', 'cube'}
READ = {'1d', '1d_array', '2d', '2d_array', '3d', '2d_ms', 'buffer'}
WRITE = {'1d', '2d', '2d_array', '3d', 'cube', 'buffer'}
HEIGHT = {'2d', '2d_array', '3d', 'cube', '2d_ms'}
ARRAY_SIZE = {'1d_array', '2d_array', 'cube_array'}
MIPS = {'2d', '2d_array', '3d', 'cube'}
WIDTH_NO_LOD = {'2d_ms', 'buffer'}


def handle(k):
    return '__MSL_DEVICE _%s_t *' % KINDS[k][1]


def emit():
    out = ['// Generated by gen_textures.py: MSL textures as AIR calls.', '#pragma once',
           '// From Metal 3.2 a texture type has the memory coherence parameter (and an',
           '// enable_if slot) Xcode\'s stdlib has, which its mangled names carry.',
           '#if __METAL_VERSION__ >= 320',
           '#define __MSL_TEXTURE_PARAMS , memory_coherence __C = memory_coherence::memory_coherence_threadgroup, class = void',
           '#else',
           '#define __MSL_TEXTURE_PARAMS',
           '#endif']
    opaque = sorted({'_%s_t' % v[1] for v in KINDS.values()} | {'_depth_2d_t', '_depth_2d_array_t', '_depth_cube_t', '_depth_2d_ms_t'})
    out.append('}  // namespace metal')
    out.append(' '.join('struct %s;' % o for o in opaque))
    out.append('namespace metal {')
    out.append('struct level { float lod; ' + AI + ' level(float l) : lod(l) {} };')
    out.append('struct bias { float value; ' + AI + ' bias(float b) : value(b) {} };')
    out.append('struct min_lod_clamp { float value; ' + AI + ' min_lod_clamp(float c) : value(c) {} };')
    out.append('enum class component { x = 0, y = 1, z = 2, w = 3 };')
    for k, (msl, air, cs, cr, arr, off, mips) in KINDS.items():
        h = handle(k)
        for T, (sfx, V, R) in ELEMS.items():
            tag = T
            # sample
            if k in SAMPLE:
                a = ', uint' if arr else ''
                if off == 'fixed1d':
                    params, args = '%s, %s, %s%s, bool, int, bool, float, float, int' % (h, '__MSL_CONSTANT _sampler_t *', cs, a), 'c%s, false, 0, lv, l, clamp, 0'
                elif off:
                    params, args = '%s, %s, %s%s, bool, %s, bool, float, float, int' % (h, '__MSL_CONSTANT _sampler_t *', cs, a, off), 'c%s, true, o, lv, l, clamp, 0'
                else:
                    params, args = '%s, %s, %s%s, bool, float, float, int' % (h, '__MSL_CONSTANT _sampler_t *', cs, a), 'c%s, lv, l, clamp, 0'
                fn = '__air_sample_%s_%s' % (air, sfx.replace('.', '_'))
                out.append('extern "C" %s %s(%s) __AIR("air.sample_%s.%s");' % (R, fn, params, air, sfx))
                o = ', %s o' % off if off and off != 'fixed1d' else ''
                out.append('%s inline %s __sample_%s(%s t, sampler s, %s c%s%s, bool lv, float l, float clamp, %s) { return %s(t, s.__s, %s).v; }'
                           % (AI, V, k, h, cs, ', uint a' if arr else '', o, T, fn, args % (', a' if arr else '')))
            if k == '2d' and T == 'float':
                out.append('extern "C" __ret_v4f32 __air_sample_texture_2d_grad_v4f32(%s, __MSL_CONSTANT _sampler_t *, float2, float2, float2, float, bool, int2, int) __AIR("air.sample_texture_2d_grad.v4f32");' % h)
            if k in GATHER:
                a = ', uint' if arr else ''
                fn = '__air_gather_%s_%s' % (air, sfx.replace('.', '_'))
                if off:
                    out.append('extern "C" %s %s(%s, __MSL_CONSTANT _sampler_t *, %s%s, bool, %s, int, int) __AIR("air.gather_%s.%s");' % (R, fn, h, cs, a, off, air, sfx))
                    out.append('%s inline %s __gather_%s(%s t, sampler s, %s c%s, %s o, int comp, %s) { return %s(t, s.__s, c%s, true, o, comp, 0).v; }'
                               % (AI, V, k, h, cs, ', uint a' if arr else '', off, T, fn, ', a' if arr else ''))
                else:
                    out.append('extern "C" %s %s(%s, __MSL_CONSTANT _sampler_t *, %s%s, int, int) __AIR("air.gather_%s.%s");' % (R, fn, h, cs, a, air, sfx))
                    out.append('%s inline %s __gather_%s(%s t, sampler s, %s c%s, int comp, %s) { return %s(t, s.__s, c%s, comp, 0).v; }'
                               % (AI, V, k, h, cs, ', uint a' if arr else '', T, fn, ', a' if arr else ''))
            if k in READ:
                fn = '__air_read_%s_%s' % (air, sfx.replace('.', '_'))
                if k == '2d_ms':
                    out.append('extern "C" %s %s(%s, __MSL_CONSTANT _sampler_t *, uint2, uint, int) __AIR("air.read_%s.%s");' % (R, fn, h, air, sfx))
                    out.append('%s inline %s __read_%s(%s t, uint2 c, uint smp, int acc, %s) { return %s(t, __air_get_read_sampler(), c, smp, acc).v; }' % (AI, V, k, h, T, fn))
                elif k == 'buffer':
                    out.append('extern "C" %s %s(%s, __MSL_CONSTANT _sampler_t *, uint, int) __AIR("air.read_%s.%s");' % (R, fn, h, air, sfx))
                    out.append('%s inline %s __read_%s(%s t, uint c, int acc, %s) { return %s(t, __air_get_read_sampler(), c, acc).v; }' % (AI, V, k, h, T, fn))
                elif k in ('1d', '1d_array'):
                    a = ', uint' if arr else ''
                    out.append('extern "C" %s %s(%s, __MSL_CONSTANT _sampler_t *, uint%s, uint, int) __AIR("air.read_%s.%s");' % (R, fn, h, a, air, sfx))
                    out.append('%s inline %s __read_%s(%s t, uint c%s, uint lod, int acc, %s) { return %s(t, __air_get_read_sampler(), c%s, lod, acc).v; }'
                               % (AI, V, k, h, ', uint a' if arr else '', T, fn, ', a' if arr else ''))
                else:
                    a = ', uint' if arr else ''
                    out.append('extern "C" %s %s(%s, __MSL_CONSTANT _sampler_t *, %s%s, %s, uint, int) __AIR("air.read_%s.%s");' % (R, fn, h, cr, a, cr, air, sfx))
                    out.append('%s inline %s __read_%s(%s t, %s c%s, uint lod, int acc, %s) { return %s(t, __air_get_read_sampler(), c%s, %s{}, lod, acc).v; }'
                               % (AI, V, k, h, cr, ', uint a' if arr else '', T, fn, ', a' if arr else '', cr))
            if k in WRITE:
                fn = '__air_write_%s_%s' % (air, sfx.replace('.', '_'))
                if k == 'buffer':
                    out.append('extern "C" void %s(%s, uint, %s, int) __AIR("air.write_%s.%s");' % (fn, h, V, air, sfx))
                    out.append('%s inline void __write_%s(%s t, %s v, uint c, int acc) { %s(t, c, v, acc); }' % (AI, k, h, V, fn))
                else:
                    a = ', uint' if (arr or k == 'cube') else ''
                    out.append('extern "C" void %s(%s, %s%s, %s, uint, int) __AIR("air.write_%s.%s");' % (fn, h, cr, a, V, air, sfx))
                    out.append('%s inline void __write_%s(%s t, %s v, %s c%s, uint lod, int acc) { %s(t, c%s, v, lod, acc); }'
                               % (AI, k, h, V, cr, ', uint a' if a else '', fn, ', a' if a else ''))
        # queries
        out.append('extern "C" uint __air_get_width_%s(%s%s) __AIR("air.get_width_%s");' % (air, h, '' if k in WIDTH_NO_LOD else ', uint', air))
        if k in HEIGHT:
            out.append('extern "C" uint __air_get_height_%s(%s%s) __AIR("air.get_height_%s");' % (air, h, '' if k in WIDTH_NO_LOD else ', uint', air))
        if k == '3d':
            out.append('extern "C" uint __air_get_depth_%s(%s, uint) __AIR("air.get_depth_%s");' % (air, h, air))
        if k in ARRAY_SIZE:
            out.append('extern "C" uint __air_get_array_size_%s(%s) __AIR("air.get_array_size_%s");' % (air, h, air))
        if k in MIPS:
            out.append('extern "C" uint __air_get_num_mip_levels_%s(%s) __AIR("air.get_num_mip_levels_%s");' % (air, h, air))
        if k == '2d_ms':
            out.append('extern "C" uint __air_get_num_samples_%s(%s) __AIR("air.get_num_samples_%s");' % (air, h, air))
        if k == '2d':
            out.append('extern "C" void __air_fence_%s(%s) __AIR("air.fence_%s");' % (air, h, air))
        # the class
        dflt = 'access::read' if k in ('2d_ms', 'buffer') else 'access::sample'
        m = ['template <class T, access A = %s __MSL_TEXTURE_PARAMS> struct %s {' % (dflt, msl), '  %s__t;' % h]
        lod = '' if k in WIDTH_NO_LOD else 'uint lod = 0'
        lodarg = '' if k in WIDTH_NO_LOD else ', lod'
        m.append('  %s uint get_width(%s) const { return __air_get_width_%s(__t%s); }' % (AI, lod, air, lodarg))
        if k in HEIGHT:
            m.append('  %s uint get_height(%s) const { return __air_get_height_%s(__t%s); }' % (AI, lod, air, lodarg))
        if k == '3d':
            m.append('  %s uint get_depth(uint lod = 0) const { return __air_get_depth_%s(__t, lod); }' % (AI, air))
        if k in ARRAY_SIZE:
            m.append('  %s uint get_array_size() const { return __air_get_array_size_%s(__t); }' % (AI, air))
        if k in MIPS:
            m.append('  %s uint get_num_mip_levels() const { return __air_get_num_mip_levels_%s(__t); }' % (AI, air))
        if k == '2d_ms':
            m.append('  %s uint get_num_samples() const { return __air_get_num_samples_%s(__t); }' % (AI, air))
        if k == '2d':
            m.append('  %s void fence() const { __air_fence_%s(__t); }' % (AI, air))
        V = 'typename __texel<T>::v4'
        if k in SAMPLE:
            a, aa = (', uint a', ', a') if arr else ('', '')
            o0 = ', %s{}' % off if off and off != 'fixed1d' else ''
            m.append('  %s %s sample(sampler s, %s c%s) const { return __sample_%s(__t, s, c%s%s, false, 0.0f, 0.0f, T()); }' % (AI, V, cs, a, k, aa, o0))
            m.append('  %s %s sample(sampler s, %s c%s, level l) const { return __sample_%s(__t, s, c%s%s, true, l.lod, 0.0f, T()); }' % (AI, V, cs, a, k, aa, o0))
            m.append('  %s %s sample(sampler s, %s c%s, bias b) const { return __sample_%s(__t, s, c%s%s, false, b.value, 0.0f, T()); }' % (AI, V, cs, a, k, aa, o0))
            if off and off != 'fixed1d':
                m.append('  %s %s sample(sampler s, %s c%s, %s o) const { return __sample_%s(__t, s, c%s, o, false, 0.0f, 0.0f, T()); }' % (AI, V, cs, a, off, k, aa))
                m.append('  %s %s sample(sampler s, %s c%s, level l, %s o) const { return __sample_%s(__t, s, c%s, o, true, l.lod, 0.0f, T()); }' % (AI, V, cs, a, off, k, aa))
                m.append('  %s %s sample(sampler s, %s c%s, bias b, %s o) const { return __sample_%s(__t, s, c%s, o, false, b.value, 0.0f, T()); }' % (AI, V, cs, a, off, k, aa))
            if k == '2d':
                m.append('  %s float4 sample(sampler s, float2 c, gradient2d g) const { return __air_sample_texture_2d_grad_v4f32(__t, s.__s, c, g.dPdx, g.dPdy, 0.0f, true, int2{0, 0}, 0).v; }' % AI)
        if k in GATHER:
            a, aa = (', uint a', ', a') if arr else ('', '')
            if off:
                m.append('  %s %s gather(sampler s, %s c%s, %s o = %s{}, component comp = component::x) const { return __gather_%s(__t, s, c%s, o, int(comp), T()); }' % (AI, V, cs, a, off, off, k, aa))
            else:
                m.append('  %s %s gather(sampler s, %s c%s, component comp = component::x) const { return __gather_%s(__t, s, c%s, int(comp), T()); }' % (AI, V, cs, a, k, aa))
        if k in READ:
            if k == '2d_ms':
                m.append('  %s %s read(uint2 c, uint smp) const { return __read_%s(__t, c, smp, int(A), T()); }' % (AI, V, k))
            elif k == 'buffer':
                m.append('  %s %s read(uint c) const { return __read_%s(__t, c, int(A), T()); }' % (AI, V, k))
            else:
                a, aa = (', uint a', ', a') if arr else ('', '')
                m.append('  %s %s read(%s c%s, uint lod = 0) const { return __read_%s(__t, c%s, lod, int(A), T()); }' % (AI, V, cr, a, k, aa))
                if cr == 'uint2':  # ushort2 and int2 coordinates convert
                    m.append('  %s %s read(ushort2 c%s, uint lod = 0) const { return read(uint2(c.x, c.y)%s, lod); }' % (AI, V, a, aa))
        if k in WRITE:
            if k == 'buffer':
                m.append('  %s void write(%s v, uint c) const { __write_%s(__t, v, c, int(A)); }' % (AI, V, k))
            else:
                a, aa = (', uint a', ', a') if (arr or k == 'cube') else ('', '')
                m.append('  %s void write(%s v, %s c%s, uint lod = 0) const { __write_%s(__t, v, c%s, lod, int(A)); }' % (AI, V, cr, a, k, aa))
        m.append('};')
        out.extend(m)
    # depth textures (float only)
    D2, D2A, DC, DMS = ('__MSL_DEVICE _depth_2d_t *', '__MSL_DEVICE _depth_2d_array_t *', '__MSL_DEVICE _depth_cube_t *', '__MSL_DEVICE _depth_2d_ms_t *')
    S = '__MSL_CONSTANT _sampler_t *'
    out += [
        'extern "C" __ret_f32 __air_sample_depth_2d_f32(%s, %s, int, float2, bool, int2, bool, float, float, int) __AIR("air.sample_depth_2d.f32");' % (D2, S),
        'extern "C" __ret_f32 __air_sample_compare_depth_2d_f32(%s, %s, int, float2, float, bool, int2, bool, float, float, int) __AIR("air.sample_compare_depth_2d.f32");' % (D2, S),
        'extern "C" __ret_f32 __air_read_depth_2d_f32(%s, %s, int, uint2, uint2, uint, int) __AIR("air.read_depth_2d.f32");' % (D2, S),
        'extern "C" __ret_v4f32 __air_gather_depth_2d_v4f32(%s, %s, int, float2, bool, int2, int) __AIR("air.gather_depth_2d.v4f32");' % (D2, S),
        'extern "C" __ret_v4f32 __air_gather_compare_depth_2d_f32(%s, %s, int, float2, float, bool, int2, int) __AIR("air.gather_compare_depth_2d.f32");' % (D2, S),
        'extern "C" uint __air_get_width_depth_2d(%s, uint) __AIR("air.get_width_depth_2d");' % D2,
        'extern "C" uint __air_get_height_depth_2d(%s, uint) __AIR("air.get_height_depth_2d");' % D2,
        'template <class T, access A = access::sample __MSL_TEXTURE_PARAMS> struct depth2d {',
        '  %s__t;' % D2,
        '  %s float sample(sampler s, float2 c, int2 o = int2{}) const { return __air_sample_depth_2d_f32(__t, s.__s, 1, c, true, o, false, 0.0f, 0.0f, 0).v; }' % AI,
        '  %s float sample(sampler s, float2 c, level l, int2 o = int2{}) const { return __air_sample_depth_2d_f32(__t, s.__s, 1, c, true, o, true, l.lod, 0.0f, 0).v; }' % AI,
        '  %s float sample_compare(sampler s, float2 c, float r, int2 o = int2{}) const { return __air_sample_compare_depth_2d_f32(__t, s.__s, 1, c, r, true, o, false, 0.0f, 0.0f, 0).v; }' % AI,
        '  %s float sample_compare(sampler s, float2 c, float r, level l, int2 o = int2{}) const { return __air_sample_compare_depth_2d_f32(__t, s.__s, 1, c, r, true, o, true, l.lod, 0.0f, 0).v; }' % AI,
        '  %s float read(uint2 c, uint lod = 0) const { return __air_read_depth_2d_f32(__t, __air_get_read_sampler(), 1, c, uint2{}, lod, int(A)).v; }' % AI,
        '  %s float4 gather(sampler s, float2 c, int2 o = int2{}) const { return __air_gather_depth_2d_v4f32(__t, s.__s, 1, c, true, o, 0).v; }' % AI,
        '  %s float4 gather_compare(sampler s, float2 c, float r, int2 o = int2{}) const { return __air_gather_compare_depth_2d_f32(__t, s.__s, 1, c, r, true, o, 0).v; }' % AI,
        '  %s uint get_width(uint lod = 0) const { return __air_get_width_depth_2d(__t, lod); }' % AI,
        '  %s uint get_height(uint lod = 0) const { return __air_get_height_depth_2d(__t, lod); }' % AI,
        '};',
        'extern "C" __ret_f32 __air_sample_depth_2d_array_f32(%s, %s, int, float2, uint, bool, int2, bool, float, float, int) __AIR("air.sample_depth_2d_array.f32");' % (D2A, S),
        'extern "C" __ret_f32 __air_sample_compare_depth_2d_array_f32(%s, %s, int, float2, uint, float, bool, int2, bool, float, float, int) __AIR("air.sample_compare_depth_2d_array.f32");' % (D2A, S),
        'extern "C" uint __air_get_array_size_depth_2d_array(%s) __AIR("air.get_array_size_depth_2d_array");' % D2A,
        'template <class T, access A = access::sample __MSL_TEXTURE_PARAMS> struct depth2d_array {',
        '  %s__t;' % D2A,
        '  %s float sample(sampler s, float2 c, uint a, int2 o = int2{}) const { return __air_sample_depth_2d_array_f32(__t, s.__s, 1, c, a, true, o, false, 0.0f, 0.0f, 0).v; }' % AI,
        '  %s float sample_compare(sampler s, float2 c, uint a, float r, int2 o = int2{}) const { return __air_sample_compare_depth_2d_array_f32(__t, s.__s, 1, c, a, r, true, o, false, 0.0f, 0.0f, 0).v; }' % AI,
        '  %s uint get_array_size() const { return __air_get_array_size_depth_2d_array(__t); }' % AI,
        '};',
        'extern "C" __ret_f32 __air_sample_depth_cube_f32(%s, %s, int, float3, bool, float, float, int) __AIR("air.sample_depth_cube.f32");' % (DC, S),
        'extern "C" __ret_f32 __air_sample_compare_depth_cube_f32(%s, %s, int, float3, float, bool, float, float, int) __AIR("air.sample_compare_depth_cube.f32");' % (DC, S),
        'template <class T, access A = access::sample __MSL_TEXTURE_PARAMS> struct depthcube {',
        '  %s__t;' % DC,
        '  %s float sample(sampler s, float3 c) const { return __air_sample_depth_cube_f32(__t, s.__s, 1, c, false, 0.0f, 0.0f, 0).v; }' % AI,
        '  %s float sample_compare(sampler s, float3 c, float r) const { return __air_sample_compare_depth_cube_f32(__t, s.__s, 1, c, r, false, 0.0f, 0.0f, 0).v; }' % AI,
        '};',
        'extern "C" __ret_f32 __air_read_depth_2d_ms_f32(%s, %s, int, uint2, uint, int) __AIR("air.read_depth_2d_ms.f32");' % (DMS, S),
        'extern "C" uint __air_get_num_samples_depth_2d_ms(%s) __AIR("air.get_num_samples_depth_2d_ms");' % DMS,
        'template <class T, access A = access::read __MSL_TEXTURE_PARAMS> struct depth2d_ms {',
        '  %s__t;' % DMS,
        '  %s float read(uint2 c, uint smp) const { return __air_read_depth_2d_ms_f32(__t, __air_get_read_sampler(), 1, c, smp, int(A)).v; }' % AI,
        '  %s uint get_num_samples() const { return __air_get_num_samples_depth_2d_ms(__t); }' % AI,
        '};',
    ]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    print(emit(), end='')
