def bal(tree, depth, nid=[0], fi=0, base_val=1.0):
    # balanced tree, BFS ids
    nodes = []
    n_int = 2**depth - 1
    for i in range(2**(depth+1) - 1):
        if i < n_int: nodes.append(B(tree, i, fi, float(i)+0.5, 2*i+1, 2*i+2))
        else: nodes.append(L(tree, i, base_val + i))
    return nodes
