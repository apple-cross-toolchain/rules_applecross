reg('S5_3t', ch(0,1,[[(0,1.0)],[(1,2.0),(2,3.0)]]) + ch(1,2,[[(4,1.0)],[(5,2.0),(2,3.0)],[(1,7.0)]]) + ch(2,1,[[(3,1.0)],[(0,2.0)]]), npd=6)
