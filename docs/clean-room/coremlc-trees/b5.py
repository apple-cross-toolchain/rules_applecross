from probe import *
def ch(t, n, vals, start=1.0):
    # chain with n internal nodes, n+1 leaves; vals: list of n+1 ev lists
    nodes=[]; it=iter(vals)
    for k in range(n):
        i=2*k
        if k<n-1: nodes += [B(t,i,0,start+k,i+2,i+1), L(t,i+1,next(it))]
        else: nodes += [B(t,i,0,start+k,i+1,i+2), L(t,i+1,next(it)), L(t,i+2,next(it))]
    return nodes
reg('S5_c3', ch(0,3,[[(0,1.0)],[(1,2.0),(2,3.0)],[(5,4.0)],[(3,5.0)]]), npd=6)
